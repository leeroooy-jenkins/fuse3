package fuse;

/**
 * Побочное действие над потоком записей. SpyFs сам решает все задачи файловой системы -
 * открыть файл, отдать байты на диск, прочитать, закрыть; экшен в это не вмешивается и
 * ничего в ответ не сообщает. Ему лишь показывают каждую запись, прошедшую через ФС,
 * а он делает с ней что-то своё: считает части, шлёт в S3, пишет в лог.
 * <p>
 * Экшены перечислены в конструкторе SpyFs и вызываются в порядке объявления. Каждый хранит
 * своё состояние на открытый файл сам, ключом служит `fh` - номер file handle, который SpyFs
 * выдал ядру в open()/create() и получает обратно в каждом следующем вызове.
 * <p>
 * Сейчас всё выполняется синхронно, прямо внутри вызова ядра, но контракт этого не требует:
 * экшену отдают копию байтов, которой он владеет, так что складывать её в очередь и
 * разбирать в фоне ему никто не мешает.
 */
public interface Action {

    /**
     * Позиционная запись: `data` легли в файл начиная со смещения `offset`. К моменту вызова
     * байты уже на диске. Приходить по порядку они не обязаны - что с этим делать, экшен
     * решает сам.
     */
    void write(String path, long fh, long offset, byte[] data);

    /**
     * Файл закрыт, больше записей по этому `fh` не будет: пора дописать хвост и освободить
     * состояние. Единственное событие, кроме самих записей, о котором SpyFs сообщает экшенам,
     * и нужно оно по делу: без него S3Action не смог бы завершить multipart-загрузку, а
     * недособранные части так и остались бы висеть.
     */
    default void release(String path, long fh) {
    }
}
